class Par(NamedTuple):
    """One ``PARS`` row by name: what the open cells of a column usually end up with."""

    counts: tuple  # mean count of 1s, 2s, ... 6s in rows 1-6
    count_vars: tuple  # variance of those six counts
    high: float  # + mean
    high_sd: float
    low: float  # - mean
    low_sd: float
    bottom: tuple  # mean K, F, P, 60

    @classmethod
    def from_row(cls, row: tuple) -> Par:
        return cls(row[:6], row[6:12], *row[12:16], row[16:20])

    def row(self) -> tuple:
        return (*self.counts, *self.count_vars, self.high, self.high_sd, self.low, self.low_sd, *self.bottom)


def _normal_cdf(z: float) -> float:
    return 0.5 * (1.0 + erf(z / sqrt(2.0)))


def _positive_mean(mean: float, sd: float) -> float:
    """Expectation of max(0, X) for X ~ N(mean, sd^2)."""
    if sd <= 1e-9:
        return max(0.0, mean)
    z = mean / sd
    return mean * _normal_cdf(z) + sd * exp(-0.5 * z * z) / sqrt(2.0 * pi)


@lru_cache(maxsize=8192)
def _column_value(cells: tuple, row: tuple, bonus_at: int) -> float:
    """Expected final total of one column; ``cells`` holds 12 values or None, ``row`` is its ``PARS`` row."""
    par = Par.from_row(row)
    written = 0
    mean = variance = 0.0
    for index in range(6):
        value = cells[index]
        if value is None:
            mean += (index + 1) * par.counts[index]
            variance += (index + 1) ** 2 * par.count_vars[index]
        else:
            written += value
    missing = bonus_at - written
    if missing <= 0:
        bonus_chance = 1.0
    elif variance <= 1e-9:
        bonus_chance = 0.0
    else:
        bonus_chance = 1.0 - _normal_cdf((missing - 0.5 - mean) / sqrt(variance))
    upper = written + mean + BONUS * bonus_chance

    ones = par.counts[0] if cells[0] is None else cells[0]
    high, low = cells[6], cells[7]
    spread = (par.high if high is None else high) - (par.low if low is None else low)
    spread_sd = sqrt((par.high_sd ** 2 if high is None else 0.0) + (par.low_sd ** 2 if low is None else 0.0))
    diff = ones * _positive_mean(spread, spread_sd)

    bottom = sum(par.bottom[offset] if cells[8 + offset] is None else cells[8 + offset] for offset in range(4))
    return upper + diff + bottom


def columns_from_board(board: dict) -> dict[str, tuple]:
    """Map a ``"row,col" -> points`` sheet to 12 values (or None) per column."""
    columns = {column: [None] * len(FIELDS) for column in COLUMNS}
    for row, field in WRITABLE_MAP.items():
        index = FIELDS.index(field)
        for column in COLUMNS:
            value = board.get(f"{row},{column}")
            if value is not None:
                try:
                    columns[column][index] = int(value)
                except (TypeError, ValueError):
                    continue
    return {column: tuple(values) for column, values in columns.items()}


def write_gain(columns: dict[str, tuple], column: str, field: str, points: int, *, hardcore: bool = False) -> float:
    """Expected change of the sheet total when ``points`` go into ``field``."""
    mode = "hardcore" if hardcore else "normal"
    written = sum(value is not None for cells in columns.values() for value in cells)
    phase = min(PHASES - 1, written * PHASES // CELLS)
    par = PARS[mode][column][phase]
    bonus_at = BONUS_AT[mode]
    cells = columns[column]
    index = FIELDS.index(field)
    after = cells[:index] + (int(points),) + cells[index + 1:]
    # A finished hit only takes the cell it was waiting for; anything else
    # uses up a flexible cell while many turns are still to come.
    flexibility = 0.0 if is_complete(field, int(points)) else (
        FLEXIBILITY[mode].get(column, 0.0) * (CELLS - written) / CELLS
    )
    return _column_value(after, par, bonus_at) - _column_value(cells, par, bonus_at) - flexibility


def is_complete(field: str, points: int) -> bool:
    """Whether more rolls cannot raise this field's points."""
    if field in ("1", "2", "3", "4", "5", "6"):
        return points == 5 * int(field)
    if field == "max":
        return points == 30
    if field == "min":
        return points == 5
    return points > 0


class _Dice(NamedTuple):
    hands: list  # every sorted hand of five dice
    index: dict  # hand -> its position in ``hands``
    keeps: list  # every sorted set of held dice
    rerolls: list  # per keep: (hand position, probability) after rolling the rest
    holds: list  # per hand: positions in ``keeps`` of the dice it can hold
    points: dict  # field -> points per hand
    four: list  # per hand: at least four of a kind
    five: list  # per hand: five of a kind


@lru_cache(maxsize=1)
def _dice() -> _Dice:
    hands = sorted({tuple(sorted(roll)) for roll in product(range(1, 7), repeat=5)})
    index = {hand: position for position, hand in enumerate(hands)}
    keeps = sorted({tuple(sorted(roll)) for count in range(6) for roll in product(range(1, 7), repeat=count)})
    keep_index = {keep: position for position, keep in enumerate(keeps)}
    rolls = [Counter(tuple(sorted(roll)) for roll in product(range(1, 7), repeat=count)) for count in range(6)]
    rerolls = [[(index[tuple(sorted(keep + roll))], count / 6 ** len(roll)) for roll, count in rolls[5 - len(keep)].items()]
               for keep in keeps]
    holds = [sorted({keep_index[tuple(hand[i] for i in range(5) if mask >> i & 1)] for mask in range(32)})
             for hand in hands]
    points = {field: [score_field_value(field, hand) for hand in hands] for field in FIELDS}
    same = [max(Counter(hand).values()) for hand in hands]
    return _Dice(hands, index, keeps, rerolls, holds, points, [n >= 4 for n in same], [n == 5 for n in same])


def _after_reroll(dice: _Dice, values: list) -> list:
    """Expected ``values`` (one per hand) after rolling, for every set of held dice."""
    return [sum(chance * values[hand] for hand, chance in outcomes) for outcomes in dice.rerolls]


def roll_on_gain(columns: dict[str, tuple], cells: list[tuple[str, str]], hand, rolls_left: int, *,
                 four_seen: bool, announced_poker: bool = False, hardcore: bool = False) -> tuple[float, tuple]:
    """Expected gain of rolling on with the best holds and then writing the best of ``cells``.

    Returns that gain and the dice to hold. ``four_seen`` says whether a four of
    a kind already lay this turn: a later Poker then only counts with five of a
    kind or in an announced ❗ Poker.
    """
    dice = _dice()
    count = len(dice.hands)
    # best[seen][hand]: best write after a roll, seen = a four of a kind lay before it.
    # Only a Poker tells the two apart.
    fresh, late = [-inf] * count, [-inf] * count
    poker_rule = False
    for column, field in cells:
        points = dice.points[field]
        gains = {value: write_gain(columns, column, field, value, hardcore=hardcore) for value in {0, *points}}
        void = field == "poker" and not (announced_poker and column == "ang")
        poker_rule = poker_rule or void
        for position, value in enumerate(points):
            gain = gains[value]
            if gain > fresh[position]:
                fresh[position] = gain
            if void and value and not dice.five[position]:
                gain = gains[0]
            if gain > late[position]:
                late[position] = gain
    best = (fresh, late if poker_rule else fresh)
    expected = [_after_reroll(dice, best[0]), _after_reroll(dice, best[1]) if poker_rule else None]

    def write_or_roll(seen: int) -> list:
        """Per hand: the better of writing it and holding the best dice for one more roll."""
        values = []
        for position in range(count):
            # Once a four of a kind lies, a later unannounced Poker needs five of a kind.
            after = expected[1 if seen or (poker_rule and dice.four[position]) else 0]
            values.append(max(best[seen][position], max(map(after.__getitem__, dice.holds[position]))))
        return values

    for _roll in range(rolls_left - 1):
        stay = [write_or_roll(seen) for seen in ((0, 1) if poker_rule else (0,))]
        expected = [_after_reroll(dice, stay[0]), _after_reroll(dice, stay[1]) if poker_rule else None]
    now = expected[1 if four_seen and poker_rule else 0]
    keep = max(dice.holds[dice.index[tuple(sorted(hand))]], key=now.__getitem__)
    return now[keep], dice.keeps[keep]


def recommend(previews: list[dict], columns: dict[str, tuple], *, dice, rolls_left: int, first_roll: bool,
              four_seen: bool, announced: str | None = None, hardcore: bool = False) -> int | None:
    """Index of the preview worth writing now, or None while rolling on is worth more.

    ``previews`` are the writable cells with their points (``compute_field_previews``),
    ``columns`` the active sheet as returned by :func:`columns_from_board`.
    """
    cells = tuple((preview["col"], WRITABLE_MAP[int(preview["row"])], int(preview["points"])) for preview in previews)
    sheet = tuple(columns[column] for column in COLUMNS)
    return _recommend(cells, sheet, tuple(sorted(dice)), rolls_left, first_roll, four_seen, announced, hardcore)


@lru_cache(maxsize=256)  # holding dice re-sends the same roll
def _recommend(cells: tuple, sheet: tuple, hand: tuple, rolls_left: int, first_roll: bool, four_seen: bool,
               announced: str | None, hardcore: bool) -> int | None:
    if not cells:
        return None
    columns = dict(zip(COLUMNS, sheet))
    gains = [write_gain(columns, column, field, points, hardcore=hardcore) for column, field, points in cells]
    best = max(range(len(gains)), key=gains.__getitem__)
    if rolls_left <= 0:
        return best
    open_cells = sum(value is None for values in sheet for value in values)
    targets = [(column, field) for column, field, _points in cells]
    # Unannounced ❗ cells are only writable right after the first roll.
    if first_roll and not announced and open_cells > 1:
        targets = [cell for cell in targets if cell[0] != "ang"]
    worth = -inf
    if targets:
        worth = roll_on_gain(columns, targets, hand, rolls_left, four_seen=four_seen,
                             announced_poker=announced == "poker", hardcore=hardcore)[0]
    if first_roll and not announced and not hardcore and open_cells > 1:
        for field, value in zip(FIELDS, columns["ang"]):
            if worth > gains[best]:
                break
            if value is None:
                announce = roll_on_gain(columns, [("ang", field)], hand, rolls_left, four_seen=four_seen,
                                        announced_poker=field == "poker")[0]
                worth = max(worth, announce)
    return best if gains[best] >= worth - 1e-9 else None
